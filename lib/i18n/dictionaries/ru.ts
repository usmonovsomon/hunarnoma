/**
 * Groups that are looked up by a runtime string (a form name straight from the
 * dataset, a question id) rather than a literal. They keep their known keys as
 * required, and additionally allow string indexing so callers can fall back to
 * the raw value when a key is missing.
 */
type LookupGroup = "forms" | "cities" | "regions" | "languages" | "questions";

type Fields<K extends keyof Source> = {
  -readonly [P in keyof Source[K]]: Source[K][P] extends readonly string[] ? string[] : string;
};

export type Dict = {
  -readonly [K in keyof Source]: K extends LookupGroup
    ? Fields<K> & Record<string, string>
    : Fields<K>;
};

export default ru as unknown as Dict;
